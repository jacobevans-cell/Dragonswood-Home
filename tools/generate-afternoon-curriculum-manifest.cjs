'use strict';

const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');

const root=path.resolve(__dirname,'..');
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'q1-curriculum-data.js'),'utf8'),sandbox);
vm.runInNewContext(fs.readFileSync(path.join(root,'q1-curriculum-day21-overrides.js'),'utf8'),sandbox);
vm.runInNewContext(fs.readFileSync(path.join(root,'q1-video-map.js'),'utf8'),sandbox);

const hidden=new Set([
  'I-HUM-D1-C1-A','I-HUM-D1-C2-A','I-HUM-D1-C3-A','I-HUM-D1-C4-A','I-HUM-D2-C1-A','I-HUM-D2-C2-A','I-HUM-D2-C3-A','I-HUM-D2-C4-A',
  'K-HUM-D1-C1-A','K-HUM-D1-C2-A','K-HUM-D1-C3-A','K-HUM-D1-C4-A','K-HUM-D2-C1-A','K-HUM-D2-C2-A','K-HUM-D2-C3-A','K-HUM-D2-C4-A',
  'I-Math-D1-C1-A','I-Math-D1-C2-A','I-Math-D1-C3-A','I-Math-D2-C3-A','K-Math-D1-C1-A','K-Math-D1-C2-A','K-Math-D1-C3-A','K-Math-D2-C1-A',
  'I-Science-D1-C1-A','I-Science-D1-C3-A','I-Science-D1-C4-A','K-Science-D1-C1-A','K-Science-D1-C3-A','K-Science-D1-C4-A'
]);
function supportMetadataRow(item){
  if(item.resourceUrl)return false;
  const strand=String(item.strand||'').toLowerCase(),requirement=String(item.requirement||'').trim();
  if((item.subject==='Math'||item.subject==='Science')&&(strand==='foundational skills'||strand==='vocabulary'||/teacher created|anecdotal|assessment\/ check point|assessment\/check point/.test(strand)))return true;
  return !item.resourceName&&requirement.split(/\s+/).length<=3&&/^(application|communication|benchmark|data analysis|conductor|impact|momentum|questioning|predicting|measuring)$/i.test(requirement);
}
function videoRequired(item){
  const url=String(item.resourceUrl||'').trim(),match=url.match(/\/d\/([^/?]+)/),sourceId=match?match[1]:'';
  const mapped=sourceId&&sandbox.window.DRAGONSWOOD_VIDEO_MAP?.[sourceId];
  return Boolean(mapped)||/\.mp4(?:[?#].*)?$/i.test(url)||Boolean(url&&(url.includes('google.com/videos')||/video/i.test(item.resourceName||'')));
}

const manifest={I:{},K:{}};
for(const grade of Object.keys(manifest))for(let day=3;day<=40;day++){
  manifest[grade][day]=sandbox.window.DRAGONSWOOD_DATA.items
    .filter(item=>item.grade===grade&&Number(item.day)===day&&!hidden.has(item.id)&&!supportMetadataRow(item))
    .map(item=>Object.freeze({id:item.id,videoRequired:videoRequired(item)}));
}

const output=`'use strict';\n// Generated by tools/generate-afternoon-curriculum-manifest.cjs.\nmodule.exports=Object.freeze(${JSON.stringify(manifest,null,2)});\n`;
fs.writeFileSync(path.join(root,'functions-arcade-access','curriculum-manifest.js'),output);
console.log('Generated functions-arcade-access/curriculum-manifest.js');
